-- =============================================================================
-- schema.sql  --  The store schema in PostgreSQL
-- =============================================================================
-- Same eight tables, same columns, same keys as ../../01_sqlite/04_model/schema.sql.
-- The design (which facts go in which table) doesn't change between relational
-- engines. What changes is how much of it PostgreSQL enforces:
--
--   * Real types. date for dates, numeric(10,2) for money, text for strings.
--     A value that doesn't fit its type is an error, not a "preference".
--   * Foreign keys are always enforced: there is no PRAGMA to forget.
--   * ON DELETE CASCADE / RESTRICT work as written.
--   * New purchase ids come from an identity column, not a rowid alias.
--
-- This file creates no secondary indexes. ../05_load/indexes.sql adds the same
-- ten SQLite's idx_* databases have; noidx_* skips that step. Like SQLite,
-- PostgreSQL does NOT index foreign-key columns for you.
--
-- No schema names appear below: the tables go in whichever schema comes first
-- in search_path. build_postgres.py sets it to idx_1m, noidx_10k, and so on;
-- rebuild.sql sets it to classroom.
-- =============================================================================

DROP VIEW  IF EXISTS purchase_details;
DROP TABLE IF EXISTS monthly_sales;
DROP TABLE IF EXISTS purchases;
DROP TABLE IF EXISTS cards;
DROP TABLE IF EXISTS customers;
DROP TABLE IF EXISTS zipcodes;
DROP TABLE IF EXISTS states;
DROP TABLE IF EXISTS card_types;
DROP TABLE IF EXISTS departments;
DROP TABLE IF EXISTS products;

-- Lookup tables: natural keys, the value is the key.
CREATE TABLE states (
    state_code  text PRIMARY KEY
                CHECK (length(state_code) = 2 AND state_code = upper(state_code))
);

CREATE TABLE card_types  (card_type  text PRIMARY KEY);
CREATE TABLE departments (department text PRIMARY KEY);

CREATE TABLE zipcodes (
    zipcode     text PRIMARY KEY,
    state_code  text NOT NULL
                REFERENCES states (state_code) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE customers (
    customer_id integer PRIMARY KEY,
    first_name  text NOT NULL,
    last_name   text NOT NULL,
    email       text NOT NULL UNIQUE CHECK (email LIKE '%_@_%.__%'),
    address     text NOT NULL,
    zipcode     text NOT NULL
                REFERENCES zipcodes (zipcode) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE cards (
    card_id     integer PRIMARY KEY,
    customer_id integer NOT NULL
                REFERENCES customers (customer_id) ON UPDATE CASCADE ON DELETE CASCADE,
    card_type   text NOT NULL
                REFERENCES card_types (card_type) ON UPDATE CASCADE ON DELETE RESTRICT,
    card_number text NOT NULL UNIQUE
);

CREATE TABLE products (
    product_id   integer PRIMARY KEY,
    product_name text NOT NULL UNIQUE,
    unit_price   numeric(10, 2) NOT NULL CHECK (unit_price >= 0)
);

-- GENERATED BY DEFAULT lets the loaders insert the source ids as they are;
-- an INSERT that leaves purchase_id out (Q15) gets the next number.
-- The loaders move the counter past the loaded rows with setval().
CREATE TABLE purchases (
    purchase_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   integer NOT NULL
                  REFERENCES customers (customer_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    card_id       integer NOT NULL
                  REFERENCES cards (card_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    product_id    integer NOT NULL
                  REFERENCES products (product_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    department    text NOT NULL
                  REFERENCES departments (department) ON UPDATE CASCADE ON DELETE RESTRICT,
    amount        numeric(10, 2) NOT NULL CHECK (amount >= 0),
    purchase_date date NOT NULL
);

-- Pre-aggregated rollup for the /fast versions of Q13 and Q14. A snapshot:
-- purchases inserted later don't appear here until it's rebuilt.
CREATE TABLE monthly_sales (
    month         text NOT NULL,          -- 'YYYY-MM', the same text as SQLite's
    state_code    text NOT NULL,
    department    text NOT NULL,
    num_purchases integer NOT NULL,
    revenue       numeric(12, 2) NOT NULL,
    PRIMARY KEY (month, state_code, department)
);

CREATE VIEW purchase_details AS
SELECT pu.purchase_id, pu.purchase_date, c.customer_id,
       c.first_name || ' ' || c.last_name AS customer_name,
       c.email, c.address, c.zipcode, z.state_code,
       pr.product_name, pu.department, pu.amount, ct.card_type
FROM purchases  pu
JOIN customers  c  ON c.customer_id = pu.customer_id
JOIN zipcodes   z  ON z.zipcode     = c.zipcode
JOIN products   pr ON pr.product_id = pu.product_id
JOIN cards      cd ON cd.card_id    = pu.card_id
JOIN card_types ct ON ct.card_type  = cd.card_type;
